package com.contentaggregation.content.enums;

/**
 * Enumeration of sentiment analysis results for content.
 *
 * <p>Sentiment values:
 * <ul>
 *   <li>POSITIVE: Content has positive sentiment</li>
 *   <li>NEGATIVE: Content has negative sentiment</li>
 *   <li>NEUTRAL: Content has neutral sentiment</li>
 * </ul>
 */
public enum Sentiment {
    POSITIVE,
    NEGATIVE,
    NEUTRAL
}
