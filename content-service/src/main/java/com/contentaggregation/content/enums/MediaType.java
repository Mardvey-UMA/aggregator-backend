package com.contentaggregation.content.enums;

/**
 * Enumeration of media types that can be attached to content.
 *
 * <p>Supported media types:
 * <ul>
 *   <li>VIDEO: Video content (mp4, webm, etc.)</li>
 *   <li>IMAGE: Single image</li>
 *   <li>GALLERY: Multiple images</li>
 *   <li>AUDIO: Audio content (mp3, ogg, etc.)</li>
 * </ul>
 */
public enum MediaType {
    VIDEO,
    IMAGE,
    GALLERY,
    AUDIO
}
